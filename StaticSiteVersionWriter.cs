using System.Text.RegularExpressions;

namespace UpdateManager.StaticSiteManagementCoreLibrary;

public partial class StaticSiteVersionWriter : IStaticSiteVersionWriter
{
    public async Task WriteVersionAsync(
        string projectPath,
        string version)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(projectPath);
        ArgumentException.ThrowIfNullOrWhiteSpace(version);

        if (MyRegex.IsMatch(version) == false)
        {
            throw new InvalidOperationException(
                $"Invalid static-site version: {version}");
        }

        projectPath = Path.GetFullPath(projectPath);

        if (File.Exists(projectPath) == false)
        {
            throw new FileNotFoundException(
                "The static-site project was not found.",
                projectPath);
        }

        string directory = Path.GetDirectoryName(projectPath)!;

        string workerPath = Path.Combine(
            directory,
            "wwwroot",
            "service-worker.published.js");

        if (File.Exists(workerPath) == false)
        {
            throw new FileNotFoundException(
                "Prepare the published service worker before writing its version.",
                workerPath);
        }

        XDocument document = XDocument.Load(projectPath);

        string projectNamespace = document.Descendants()
            .FirstOrDefault(x =>
                x.Name.LocalName == "RootNamespace" &&
                string.IsNullOrWhiteSpace(x.Value) == false)
            ?.Value.Trim()
            ?? Path.GetFileNameWithoutExtension(projectPath);

        if (MyRegex1.IsMatch(projectNamespace) == false)
        {
            throw new InvalidOperationException(
                $"Set a valid RootNamespace in {projectPath}.");
        }

        string worker = await File.ReadAllTextAsync(workerPath);

        Regex declaration = MyRegex2;

        int matches = declaration.Count(worker);

        if (matches > 1)
        {
            throw new InvalidOperationException(
                $"Multiple version declarations were found in {workerPath}.");
        }

        string javascriptVersion = $"const version = '{version}';";

        string updatedWorker = matches == 1
            ? declaration.Replace(worker, javascriptVersion)
            : javascriptVersion + Environment.NewLine + worker;

        string csharp = $$"""
            // <auto-generated />
            namespace {{projectNamespace}};
            public static class StaticSiteVersion
            {
                public const string Version = "{{version}}";
            }
            """;

        string versionPath = Path.Combine(
            directory,
            "StaticSiteVersion.g.cs");

        await WriteIfChangedAsync(
            versionPath,
            csharp + Environment.NewLine);

        await WriteIfChangedAsync(workerPath, updatedWorker);
    }

    private static async Task WriteIfChangedAsync(
        string path,
        string content)
    {
        if (File.Exists(path))
        {
            string existing = await File.ReadAllTextAsync(path);

            if (existing == content)
            {
                return;
            }
        }

        await File.WriteAllTextAsync(path, content);
    }

    [GeneratedRegex(@"^[0-9]+\.[0-9]+$")]
    private static partial Regex MyRegex { get; }

    [GeneratedRegex(@"^[ \t]*const[ \t]+version[ \t]*=[ \t]*['""][^'""\r\n]*['""][ \t]*;[ \t]*\r?$", RegexOptions.Multiline)]
    private static partial Regex MyRegex2 { get; }

    [GeneratedRegex(@"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$")]
    private static partial Regex MyRegex1 { get; }
}